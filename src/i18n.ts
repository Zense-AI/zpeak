const DICTS: Record<Lang, Dict> = { en, "zh-hant": zhHant, "zh-hans": zhHans };

export function systemLang(): Lang {
  const l = (navigator.language || "en").toLowerCase();
  if (l.startsWith("zh")) {
    return /hans|cn|sg/.test(l) ? "zh-hans" : "zh-hant";
  }
  return "en";
}

export function translator(lang: Lang) {
  const dict = DICTS[lang];
  const t = (key: keyof Dict, vars: Record<string, string | number> = {}) =>
    dict[key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
  const err = (code: string | null | undefined) => {
    const key = `err_${code}` as keyof Dict;
    return key in dict ? dict[key] : dict.err_default;
  };
  return { t, err };
}

export type T = ReturnType<typeof translator>["t"];
